// One-shot precomputation: generate the 12 curated levels using the full
// generator + multi-trial selector, then dump as a static ES module so the
// browser doesn't have to redo this work on every page load.
//
// Run: node tools/generate-levels-data.mjs
import { LEVEL_CONFIGS, makeMazeLevel, TIME, analyzeDifficulty } from "../js/levels.js";
import fs from "node:fs/promises";

const t0 = Date.now();
const out = LEVEL_CONFIGS.map((cfg, i) => {
  const seed = (i + 1) * 101 + 7;
  const arrows = makeMazeLevel(
    cfg.cols, cfg.rows, cfg.count, cfg.maxBody,
    seed, cfg.palette, cfg.longBias, cfg.targetTight, cfg.depBias,
    /* fast= */ false, cfg.minArrows ?? 0, cfg.capArrows ?? Infinity,
    cfg.targetMaxChoices ?? null, cfg.coverageCap ?? null
  );
  // The auto-grow retry inside makeMazeLevel can return a maze on a
  // bigger grid than cfg.cols/rows. Recover the actual bounds from the
  // arrow cells so analyze + storage use the right dimensions.
  let actualCols = cfg.cols, actualRows = cfg.rows;
  for (const a of arrows) for (const c of a.cells) {
    if (c.x + 1 > actualCols) actualCols = c.x + 1;
    if (c.y + 1 > actualRows) actualRows = c.y + 1;
  }
  const stats = analyzeDifficulty(arrows, actualCols, actualRows);
  // Coverage = occupied / total cells.
  const occ = new Set();
  for (const a of arrows) for (const c of a.cells) occ.add(`${c.x},${c.y}`);
  const cov = occ.size / (actualCols * actualRows);
  console.log(
    `Lv ${String(i + 1).padStart(2)} ${cfg.name.padEnd(8)}: ` +
    `${String(arrows.length).padStart(3)} arrows ` +
    `(min ${cfg.minArrows}), ` +
    `${actualCols}x${actualRows}, ` +
    `cov=${(cov * 100).toFixed(0)}%, ` +
    `tight=${(stats.tightFrac * 100).toFixed(0)}%`
  );
  return {
    name: cfg.name,
    cols: actualCols,
    rows: actualRows,
    timeLimit: TIME(i + 1),
    lives: 3,
    // Compact arrow encoding: cells -> "x,y|x,y|..." (saves ~60% vs JSON)
    arrows: arrows.map(a => {
      const cells = a.cells.map(c => `${c.x},${c.y}`).join("|");
      return a.color ? { c: cells, k: a.color } : { c: cells };
    }),
  };
});

const banner = `// AUTO-GENERATED by tools/generate-levels-data.mjs — DO NOT EDIT BY HAND.
// Re-run that script if you change LEVEL_CONFIGS or the maze generator.
// Each arrow.c is "x1,y1|x2,y2|..." (head is the LAST cell).

`;

const code = `${banner}export const PRECOMPUTED_LEVELS = ${JSON.stringify(out, null, 0)};
`;

await fs.writeFile("js/levels-data.js", code);
console.log(`\nWrote js/levels-data.js (${(code.length / 1024).toFixed(1)} KB) in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
